package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"slices"
	"strings"
)

// The frontend gets its API types from the OpenAPI spec. Off-the-shelf
// generators no longer read OpenAPI v2 (what protoc-gen-openapiv2 emits), and
// our spec only uses a handful of constructs, so a small converter is simpler
// than another toolchain.
//
// The JSON shape follows the gateway marshaler in cmd/server (protojson with
// EmitUnpopulated): every field is always present, unset messages are null,
// 64-bit integers and enums are strings.

type swaggerSpec struct {
	Definitions map[string]*swaggerSchema `json:"definitions"`
}

type swaggerSchema struct {
	Type                 string                    `json:"type"`
	Format               string                    `json:"format"`
	Ref                  string                    `json:"$ref"`
	Title                string                    `json:"title"`
	Description          string                    `json:"description"`
	Enum                 []string                  `json:"enum"`
	Items                *swaggerSchema            `json:"items"`
	Properties           map[string]*swaggerSchema `json:"properties"`
	AdditionalProperties any                       `json:"additionalProperties"`
}

// swaggerToTS converts the definitions of an OpenAPI v2 spec into TypeScript
// declarations. Output is deterministic (sorted) so regeneration is diff-free.
func swaggerToTS(spec []byte) ([]byte, error) {
	var s swaggerSpec
	if err := json.Unmarshal(spec, &s); err != nil {
		return nil, fmt.Errorf("tsgen: parse spec: %w", err)
	}
	if len(s.Definitions) == 0 {
		return nil, fmt.Errorf("tsgen: spec has no definitions")
	}
	names := make([]string, 0, len(s.Definitions))
	for n := range s.Definitions {
		names = append(names, n)
	}
	slices.Sort(names)

	g := &tsWriter{defs: s.Definitions}
	g.line("// Code generated by tools/protogen from gen/openapi/api.swagger.json. DO NOT EDIT.")
	for _, n := range names {
		if err := g.definition(n, s.Definitions[n]); err != nil {
			return nil, err
		}
	}
	return g.buf.Bytes(), g.err
}

type tsWriter struct {
	buf  bytes.Buffer
	defs map[string]*swaggerSchema
	err  error
}

func (g *tsWriter) line(format string, args ...any) {
	fmt.Fprintf(&g.buf, format+"\n", args...)
}

func (g *tsWriter) doc(indent string, sc *swaggerSchema) {
	text := strings.TrimSpace(sc.Title)
	if d := strings.TrimSpace(sc.Description); d != "" {
		if text != "" {
			text += "\n"
		}
		text += d
	}
	if text == "" {
		return
	}
	text = strings.ReplaceAll(text, "*/", "* /")
	lines := strings.Split(text, "\n")
	if len(lines) == 1 {
		g.line("%s/** %s */", indent, lines[0])
		return
	}
	g.line("%s/**", indent)
	for _, l := range lines {
		g.line("%s * %s", indent, strings.TrimSpace(l))
	}
	g.line("%s */", indent)
}

func (g *tsWriter) definition(name string, sc *swaggerSchema) error {
	g.line("")
	g.doc("", sc)
	ts := tsName(name)
	switch {
	case len(sc.Enum) > 0:
		quoted := make([]string, len(sc.Enum))
		for i, v := range sc.Enum {
			quoted[i] = fmt.Sprintf("%q", v)
		}
		g.line("export type %s = %s;", ts, strings.Join(quoted, " | "))
	case sc.Type == "object" || sc.Properties != nil:
		g.line("export interface %s {", ts)
		props := make([]string, 0, len(sc.Properties))
		for p := range sc.Properties {
			props = append(props, p)
		}
		slices.SortFunc(props, func(a, b string) int { return strings.Compare(a, b) })
		for _, p := range props {
			ps := sc.Properties[p]
			t, err := g.typeOf(ps, true)
			if err != nil {
				return fmt.Errorf("tsgen: %s.%s: %w", name, p, err)
			}
			g.doc("  ", ps)
			g.line("  %s: %s;", tsKey(p), t)
		}
		if sc.AdditionalProperties != nil && sc.AdditionalProperties != false {
			g.line("  [key: string]: unknown;")
		}
		g.line("}")
	default:
		t, err := g.typeOf(sc, false)
		if err != nil {
			return fmt.Errorf("tsgen: %s: %w", name, err)
		}
		g.line("export type %s = %s;", ts, t)
	}
	return nil
}

// typeOf maps a schema to a TS type. A field referencing a message may be
// null (unset message); enums and scalars never are.
func (g *tsWriter) typeOf(sc *swaggerSchema, field bool) (string, error) {
	if sc.Ref != "" {
		target, ok := strings.CutPrefix(sc.Ref, "#/definitions/")
		def := g.defs[target]
		if !ok || def == nil {
			return "", fmt.Errorf("unresolved $ref %q", sc.Ref)
		}
		if field && len(def.Enum) == 0 {
			return tsName(target) + " | null", nil
		}
		return tsName(target), nil
	}
	switch sc.Type {
	case "string":
		// int64/uint64 are decimal strings in protojson.
		return "string", nil
	case "integer", "number":
		return "number", nil
	case "boolean":
		return "boolean", nil
	case "array":
		if sc.Items == nil {
			return "unknown[]", nil
		}
		t, err := g.typeOf(sc.Items, false)
		if err != nil {
			return "", err
		}
		return t + "[]", nil
	case "object":
		return "Record<string, unknown>", nil
	default:
		return "", fmt.Errorf("unsupported schema type %q", sc.Type)
	}
}

// tsName drops the proto package prefix ("v1Player" -> "Player") and
// capitalizes the rest ("rpcStatus" -> "RpcStatus").
func tsName(def string) string {
	n := strings.TrimPrefix(def, "v1")
	if n == "" {
		return def
	}
	return strings.ToUpper(n[:1]) + n[1:]
}

// tsKey quotes property names that are not plain identifiers ("@type").
func tsKey(k string) string {
	for i, r := range k {
		ok := r == '_' || r == '$' || ('a' <= r && r <= 'z') || ('A' <= r && r <= 'Z') || (i > 0 && '0' <= r && r <= '9')
		if !ok {
			return fmt.Sprintf("%q", k)
		}
	}
	return k
}
